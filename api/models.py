from django.contrib.auth.models import AbstractUser
from django.core.exceptions import ValidationError
from django.db import models


class User(AbstractUser):
    email = models.EmailField(unique=True)
    phone_number = models.CharField(max_length=32, blank=True)
    street_address = models.CharField(max_length=255, blank=True)
    city = models.CharField(max_length=120, blank=True)
    state = models.CharField(max_length=120, blank=True)
    country = models.CharField(max_length=120, default='Nigeria', blank=True)
    preferred_categories = models.JSONField(default=list, blank=True)
    preferred_languages = models.JSONField(default=list, blank=True)
    preferred_age_groups = models.JSONField(default=list, blank=True)
    max_distance_km = models.PositiveIntegerField(null=True, blank=True)
    email_notifications = models.BooleanField(default=True)
    event_reminders = models.BooleanField(default=True)

    USERNAME_FIELD = 'email'
    REQUIRED_FIELDS = ['username']

    # reverse relation type hints (auto-generated by Django, not visible to Pylance)
    if False:  # never executes — only here for the type checker
        from django.db.models import Manager
        events: Manager['Event']
        event_likes: Manager['EventLike']
        event_saves: Manager['EventSave']
        event_rsvps: Manager['RSVP']
        notifications: Manager['Notification']
        password_reset_tokens: Manager['PasswordResetToken']

    def __str__(self):
        return self.email



class Category(models.Model):
    name = models.CharField(max_length=120)
    slug = models.SlugField(max_length=80, unique=True)
    icon = models.CharField(max_length=40, default='zap')
    description = models.TextField(blank=True)
    is_active = models.BooleanField(default=True)
    sort_order = models.PositiveIntegerField(default=0)
    created_at = models.DateTimeField(auto_now_add=True)
    updated_at = models.DateTimeField(auto_now=True)

    class Meta:
        ordering = ['sort_order', 'name']
        verbose_name_plural = 'categories'

    def __str__(self):
        return self.name


class Event(models.Model):
    PRICING_CHOICES = (
        ('free', 'Free'),
        ('paid', 'Paid'),
    )
    APPROVAL_CHOICES = (
        ('pending', 'Pending'),
        ('approved', 'Approved'),
        ('rejected', 'Rejected'),
    )
    LANGUAGE_CHOICES = (
        ('english', 'English'),
        ('yoruba', 'Yoruba'),
        ('igbo', 'Igbo'),
        ('hausa', 'Hausa'),
        ('pidgin', 'Pidgin'),
        ('french', 'French'),
        ('multilingual', 'Multilingual'),
    )
    AGE_GROUP_CHOICES = (
        ('all_ages', 'All Ages'),
        ('children', 'Children (0-12)'),
        ('teenagers', 'Teenagers (13-19)'),
        ('young_adults', 'Young Adults (20-35)'),
        ('adults', 'Adults (36-60)'),
        ('seniors', 'Seniors (60+)'),
    )

    title = models.CharField(max_length=255)
    description = models.TextField()
    organizer = models.CharField(max_length=255, blank=True)
    date = models.DateTimeField()
    end_date = models.DateTimeField(null=True, blank=True)
    location = models.CharField(max_length=255)
    location_lat = models.DecimalField(max_digits=9, decimal_places=6, null=True, blank=True)
    location_lng = models.DecimalField(max_digits=9, decimal_places=6, null=True, blank=True)
    pricing = models.CharField(max_length=20, choices=PRICING_CHOICES)
    ticket_price = models.DecimalField(max_digits=10, decimal_places=2, null=True, blank=True)
    category = models.ForeignKey(Category, related_name='events', on_delete=models.PROTECT)
    language = models.CharField(max_length=80, choices=LANGUAGE_CHOICES)
    age_group = models.CharField(max_length=80, choices=AGE_GROUP_CHOICES)
    capacity = models.PositiveIntegerField(null=True, blank=True)
    created_by = models.ForeignKey(User, related_name='events', on_delete=models.CASCADE)
    created_by_id: int
    approval_status = models.CharField(max_length=20, choices=APPROVAL_CHOICES, default='pending')
    rejection_reason = models.TextField(blank=True)
    is_featured = models.BooleanField(default=False)
    image = models.ImageField(upload_to='events/', null=True, blank=True)
    created_at = models.DateTimeField(auto_now_add=True)
    updated_at = models.DateTimeField(auto_now=True)

    # reverse relation type hints (auto-generated by Django, not visible to Pylance)
    rsvps: models.Manager['RSVP']
    likes: models.Manager['EventLike']
    saves: models.Manager['EventSave']
    notifications: models.Manager['Notification']

    class Meta:
        ordering = ['-created_at']

    def __str__(self):
        return self.title

    def clean(self):
        errors = {}
        if self.end_date and self.date and self.end_date <= self.date:
            errors['end_date'] = ['End date must be after start date.']
        if self.pricing == 'paid' and self.ticket_price is None:
            errors['ticket_price'] = ['This field is required when pricing is paid.']
        if self.pricing == 'free' and self.ticket_price is not None:
            self.ticket_price = None
        if errors:
            raise ValidationError(errors)

    @property
    def rsvp_count(self):
        return self.rsvps.count()

    @property
    def is_full(self):
        return self.capacity is not None and self.rsvp_count >= self.capacity


